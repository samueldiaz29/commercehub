CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    customer_id VARCHAR(200) NOT NULL,
    CONSTRAINT pk_carts PRIMARY KEY (id),
    CONSTRAINT uk_carts_customer_id UNIQUE (customer_id),
    CONSTRAINT ck_carts_customer_id_not_blank CHECK (length(trim(customer_id)) > 0)
);

CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    cart_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT pk_cart_items PRIMARY KEY (id),
    CONSTRAINT fk_cart_items_carts FOREIGN KEY (cart_id) REFERENCES carts(id) ON DELETE CASCADE,
    CONSTRAINT uk_cart_items_cart_product UNIQUE (cart_id, product_id),
    CONSTRAINT ck_cart_items_quantity_positive CHECK (quantity >= 1)
);
CREATE INDEX idx_cart_items_product_id ON cart_items(product_id);
